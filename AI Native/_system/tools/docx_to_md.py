#!/usr/bin/env python3
"""Export a .docx to plain Markdown-ish text, so a gitignored handout has a diffable twin.

    env/bin/python _system/tools/docx_to_md.py 6-workshops/<session>/<final|working>/handouts/<file>.docx \
        > 6-workshops/<session>/<final|working>/handouts/<file>.md

Standard library only. Keeps paragraph text in order and renders tables as pipe rows.
Loses formatting, images and comments. Generated: edit the .docx, then re-run.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
import zipfile
from pathlib import Path
from xml.etree import ElementTree as ET

W = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"


def text(el: ET.Element) -> str:
    return "".join(t.text or "" for t in el.iter(f"{W}t"))


def render(doc: Path) -> str:
    body = ET.fromstring(zipfile.ZipFile(doc).read("word/document.xml")).find(f"{W}body")
    digest = hashlib.sha256(doc.read_bytes()).hexdigest()[:12]
    out = [
        f"<!-- GENERATED by _system/tools/docx_to_md.py from {doc.name} (sha256 {digest}…). "
        "Do not hand-edit: change the .docx and re-run. -->",
        "",
        "```text",
    ]
    for el in body:
        if el.tag == f"{W}p":
            out.append(text(el))
        elif el.tag == f"{W}tbl":
            for row in el.iter(f"{W}tr"):
                out.append("| " + " | ".join(text(c) for c in row.iter(f"{W}tc")) + " |")
    # Collapse runs of blank lines left by page-layout spacing.
    collapsed: list[str] = []
    for line in out:
        if line.strip() == "" and collapsed and collapsed[-1].strip() == "":
            continue
        collapsed.append(line.rstrip())
    return "\n".join(collapsed).rstrip() + "\n```\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("docx", type=Path)
    args = ap.parse_args()
    if not args.docx.is_file():
        sys.exit(f"no such file: {args.docx}")
    sys.stdout.write(render(args.docx))


if __name__ == "__main__":
    main()
