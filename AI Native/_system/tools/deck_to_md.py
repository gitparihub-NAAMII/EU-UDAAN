#!/usr/bin/env python3
"""Export a .pptx deck to slide-by-slide Markdown, so a gitignored binary has a diffable twin.

    env/bin/python _system/tools/deck_to_md.py 6-workshops/ai-nativity-2026/deck/ai-nativity-2026.pptx \
        > 6-workshops/ai-nativity-2026/slides.md

Standard library only (a .pptx is a zip of XML). What it keeps: every text run, in reading
order, plus speaker notes. What it cannot keep: images, diagrams, layout. Slides carrying
pictures are marked so a reader knows the text is not the whole slide.

The Markdown is generated. Edit the deck, then re-run; never hand-edit the export.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
import zipfile
from pathlib import Path
from xml.etree import ElementTree as ET

A = "{http://schemas.openxmlformats.org/drawingml/2006/main}"
P = "{http://schemas.openxmlformats.org/presentationml/2006/main}"

# Running footer repeated on every content slide — noise in a text export.
FOOTER = re.compile(r"^AI Nativity\s+·\s+NAAMII Education & Outreach\s+·\s+UDAAN$")


def paragraphs(xml: bytes) -> list[str]:
    root = ET.fromstring(xml)
    out = []
    for p in root.iter(f"{A}p"):
        text = "".join(t.text or "" for t in p.iter(f"{A}t")).strip()
        if text:
            out.append(re.sub(r"\s{2,}", "  ", text))
    return out


def picture_count(xml: bytes) -> int:
    return sum(1 for _ in ET.fromstring(xml).iter(f"{P}pic"))


def clean(lines: list[str], slide_no: int) -> list[str]:
    lines = [l for l in lines if not FOOTER.match(l)]
    # The page number is the first bare occurrence of the slide number; later ones are content.
    if str(slide_no) in lines:
        lines.remove(str(slide_no))
    # Merge short markers ("A", "1", "Q1") into the line they label.
    merged: list[str] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        if len(line) <= 3 and i + 1 < len(lines):
            merged.append(f"**{line}** — {lines[i + 1]}")
            i += 2
            continue
        merged.append(line)
        i += 1
    return merged


def render(deck: Path) -> str:
    z = zipfile.ZipFile(deck)
    names = z.namelist()
    slides = sorted(
        (n for n in names if re.fullmatch(r"ppt/slides/slide\d+\.xml", n)),
        key=lambda n: int(re.search(r"\d+", n).group()),
    )
    digest = hashlib.sha256(deck.read_bytes()).hexdigest()[:12]
    out = [
        f"<!-- GENERATED by _system/tools/deck_to_md.py from {deck.name} (sha256 {digest}…). "
        "Do not hand-edit: change the deck and re-run. -->",
        "",
        f"# {deck.stem} — slide text",
        "",
        f"{len(slides)} slides. Text only; slides marked 🖼 carry images the export cannot show.",
        "",
    ]
    # Every slide carries the same logos; only pictures beyond that baseline are content.
    counts = {name: picture_count(z.read(name)) for name in slides}
    baseline = min(counts.values(), default=0)
    for name in slides:
        n = int(re.search(r"\d+", name).group())
        xml = z.read(name)
        lines = clean(paragraphs(xml), n)
        pics = counts[name] - baseline
        if lines and lines[0].isupper() and len(lines) > 1:
            label, title, body = lines[0], lines[1], lines[2:]
            heading = f"## {n} · {title}"
        elif lines:
            heading, body = f"## {n} · {lines[0]}", lines[1:]
        else:
            heading, body = f"## {n} · (no text)", []
        out.append(heading + (" 🖼" if pics else ""))
        out.append("")
        if lines and lines[0].isupper() and len(lines) > 1:
            out += [f"<sub>{label}</sub>", ""]
        out.extend(f"{l}  " for l in body)
        notes_name = f"ppt/notesSlides/notesSlide{n}.xml"
        if notes_name in names:
            notes = [l for l in paragraphs(z.read(notes_name)) if not l.isdigit()]
            if notes:
                out += ["", "> **Speaker notes:** " + " ".join(notes)]
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("deck", type=Path)
    args = ap.parse_args()
    if not args.deck.is_file():
        sys.exit(f"no such deck: {args.deck}")
    sys.stdout.write(render(args.deck))


if __name__ == "__main__":
    main()
